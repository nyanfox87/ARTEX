function CategoryManagementSheet({
  categories,
  tasks,
  onChanged,
  onTaskMoved,
}: {
  categories: TaskCategory[];
  tasks: Task[];
  onChanged: () => void;
  onTaskMoved: (taskID: string, category: TaskCategory | null) => void;
}) {
  const [open, setOpen] = React.useState(false);
  const [selectedView, setSelectedView] = React.useState<CategoryManagementView>("new");
  const [draftName, setDraftName] = React.useState("");
  const [saving, setSaving] = React.useState(false);
  const [deleteOpen, setDeleteOpen] = React.useState(false);
  const [deleting, setDeleting] = React.useState(false);
  const [movingTaskID, setMovingTaskID] = React.useState<string | null>(null);
  const [activeTaskID, setActiveTaskID] = React.useState<string | null>(null);
  const wasOpen = React.useRef(false);
  const sensors = useSensors(
    useSensor(PointerSensor, { activationConstraint: { distance: 6 } }),
    useSensor(KeyboardSensor),
  );

  React.useEffect(() => {
    if (open && !wasOpen.current) {
      const first = categories[0];
      if (first) {
        setSelectedView(first.id);
        setDraftName(first.name);
      } else if (tasks.some((task) => task.category_id == null)) {
        setSelectedView("uncategorized");
        setDraftName("");
      } else {
        setSelectedView("new");
        setDraftName("");
      }
    }
    wasOpen.current = open;
  }, [categories, open, tasks]);

  const selectedCategory = React.useMemo(
    () =>
      typeof selectedView === "number" ? (categories.find((category) => category.id === selectedView) ?? null) : null,
    [categories, selectedView],
  );

  const uncategorizedCount = React.useMemo(() => tasks.filter((task) => task.category_id == null).length, [tasks]);

  const visibleTasks = React.useMemo(() => {
    if (selectedView === "uncategorized") return tasks.filter((task) => task.category_id == null);
    if (typeof selectedView === "number") return tasks.filter((task) => task.category_id === selectedView);
    return [];
  }, [selectedView, tasks]);

  const activeTask = React.useMemo(() => tasks.find((task) => task.id === activeTaskID) ?? null, [activeTaskID, tasks]);

  const selectCategory = (category: TaskCategory) => {
    setSelectedView(category.id);
    setDraftName(category.name);
  };

  const selectUncategorized = () => {
    setSelectedView("uncategorized");
    setDraftName("");
  };

  const startNew = () => {
    setSelectedView("new");
    setDraftName("");
  };

  async function saveCategory() {
    const name = draftName.trim();
    if (!name || saving || selectedView === "uncategorized") return;
    setSaving(true);
    try {
      if (selectedView === "new") {
        const created = await api.createTaskCategory(name);
        setSelectedView(created.id);
        setDraftName(created.name);
        toast.success("分類已建立");
      } else {
        const updated = await api.renameTaskCategory(selectedView, name);
        setDraftName(updated.name);
        toast.success("分類已更新");
      }
      onChanged();
    } catch (error) {
      toast.error(`${selectedView === "new" ? "建立" : "更新"}分類失敗：${(error as Error).message}`);
    } finally {
      setSaving(false);
    }
  }

  async function deleteCategory() {
    if (!selectedCategory || deleting) return;
    const deletedID = selectedCategory.id;
    setDeleting(true);
    try {
      await api.deleteTaskCategory(deletedID);
      const next = categories.find((category) => category.id !== deletedID);
      if (next) selectCategory(next);
      else selectUncategorized();
      toast.success("分類已刪除，關聯任務已移入未分類");
      setDeleteOpen(false);
      onChanged();
    } catch (error) {
      toast.error(`刪除分類失敗：${(error as Error).message}`);
    } finally {
      setDeleting(false);
    }
  }

  async function moveTask(task: Task, destination: string) {
    if (movingTaskID) return;
    const category =
      destination === "uncategorized" ? null : (categories.find((item) => item.id === Number(destination)) ?? null);
    if (destination !== "uncategorized" && !category) {
      toast.error("目標分類不存在，請重新整理後重試");
      return;
    }
    if (task.category_id === category?.id || (task.category_id == null && category == null)) return;

    setMovingTaskID(task.id);
    try {
      await api.updateTaskCategory(task.id, category?.id);
      onTaskMoved(task.id, category);
      toast.success(`任務 #${task.id} 已移至「${category?.name ?? "未分類"}」`);
    } catch (error) {
      toast.error(`移動任務失敗：${(error as Error).message}`);
    } finally {
      setMovingTaskID(null);
    }
  }

  function handleDragStart(event: DragStartEvent) {
    const id = String(event.active.id);
    setActiveTaskID(id.startsWith("task:") ? id.slice("task:".length) : null);
  }

  function handleDragEnd(event: DragEndEvent) {
    const activeID = String(event.active.id);
    const taskID = activeID.startsWith("task:") ? activeID.slice("task:".length) : null;
    setActiveTaskID(null);
    if (!taskID || !event.over) return;
    const destination = String(event.over.id);
    if (!destination.startsWith("category:")) return;
    const task = tasks.find((item) => item.id === taskID);
    if (!task) return;
    void moveTask(task, destination.slice("category:".length));
  }

  const saveLabel = saving ? "儲存中" : selectedView === "new" ? "建立分類" : "儲存修改";

  return (
    <>
      <Sheet open={open} onOpenChange={setOpen}>
        <SheetTrigger asChild>
          <Button size="sm" variant="outline">
            <TagsIcon data-icon="inline-start" />
            分類管理
          </Button>
        </SheetTrigger>
        <SheetContent className="grid h-full w-full! max-w-none! grid-rows-[auto_minmax(0,1fr)_auto] gap-0 overflow-hidden p-0 sm:w-[48rem]! sm:max-w-[48rem]!">
          <SheetHeader className="border-b px-6 py-5">
            <SheetTitle>任務分類管理</SheetTitle>
            <SheetDescription>分類用於任務篩選與歸檔；修改不會影響任務執行，刪除後任務會移入未分類。</SheetDescription>
          </SheetHeader>
          <DndContext
            sensors={sensors}
            onDragStart={handleDragStart}
            onDragCancel={() => setActiveTaskID(null)}
            onDragEnd={handleDragEnd}
          >
            <div className="grid min-h-0 overflow-y-auto lg:grid-cols-[15rem_minmax(0,1fr)] lg:overflow-hidden">
              <div className="flex min-h-0 flex-col border-b p-3 lg:border-r lg:border-b-0">
                <Button type="button" variant="outline" className="w-full" onClick={startNew}>
                  <PlusIcon data-icon="inline-start" />
                  新建分類
                </Button>
                <ScrollArea className="mt-2 max-h-44 lg:max-h-none lg:flex-1">
                  <div className="flex flex-col gap-1 pr-2">
                    <CategoryDropTarget
                      value="uncategorized"
                      name="未分類"
                      count={uncategorizedCount}
                      selected={selectedView === "uncategorized"}
                      disabled={movingTaskID != null}
                      onSelect={selectUncategorized}
                    />
                    {categories.map((category) => (
                      <CategoryDropTarget
                        key={category.id}
                        value={String(category.id)}
                        name={category.name}
                        count={category.task_count}
                        selected={selectedView === category.id}
                        disabled={movingTaskID != null}
                        onSelect={() => selectCategory(category)}
                      />
                    ))}
                  </div>
                </ScrollArea>
              </div>
              <ScrollArea className="min-h-0">
                <FieldGroup className="p-6">
                  {selectedView !== "uncategorized" && (
                    <Field>
                      <FieldLabel htmlFor="task-category-name">分類名稱</FieldLabel>
                      <Input
                        id="task-category-name"
                        value={draftName}
                        onChange={(event) => setDraftName(event.target.value)}
                        placeholder="例如：外網評估"
                        maxLength={80}
                        onKeyDown={(event) => {
                          if (event.key === "Enter") void saveCategory();
                        }}
                      />
                      <FieldDescription>
                        {selectedCategory
                          ? `當前有 ${selectedCategory.task_count} 個任務使用該分類。重新命名後會同步更新任務列表。`
                          : "建立後可在新建任務和任務列表篩選中使用。"}
                      </FieldDescription>
                    </Field>
                  )}
                  {selectedView !== "new" && (
                    <Field>
                      <div className="flex flex-wrap items-end justify-between gap-2">
                        <div className="flex min-w-0 flex-col gap-1">
                          <FieldLabel>{selectedCategory ? "分類任務" : "未分類任務"}</FieldLabel>
                          <FieldDescription>
                            {selectedCategory
                              ? `該分類包含 ${visibleTasks.length} 個任務。`
                              : `當前有 ${visibleTasks.length} 個任務尚未分類。`}
                          </FieldDescription>
                        </div>
                      </div>
                      {visibleTasks.length === 0 ? (
                        <Empty className="min-h-36 border">
                          <EmptyHeader>
                            <EmptyTitle>{selectedCategory ? "該分類暫無任務" : "暫無未分類任務"}</EmptyTitle>
                            <EmptyDescription>此處將在任務歸入後顯示內容。</EmptyDescription>
                          </EmptyHeader>
                        </Empty>
                      ) : (
                        <ItemGroup className="gap-2">
                          {visibleTasks.map((task) => (
                            <DraggableCategoryTask
                              key={task.id}
                              task={task}
                              moving={movingTaskID === task.id}
                              disabled={movingTaskID != null}
                            />
                          ))}
                        </ItemGroup>
                      )}
                    </Field>
                  )}
                </FieldGroup>
              </ScrollArea>
            </div>
            <DragOverlay>{activeTask ? <CategoryTaskDragPreview task={activeTask} /> : null}</DragOverlay>
          </DndContext>
          <SheetFooter className="border-t px-6 py-4 sm:flex-row sm:items-center">
            {selectedCategory && (
              <Button
                type="button"
                variant="destructive"
                className="sm:mr-auto"
                disabled={saving || deleting}
                onClick={() => setDeleteOpen(true)}
              >
                <Trash2Icon data-icon="inline-start" />
                刪除分類
              </Button>
            )}
            <Button type="button" variant="outline" onClick={() => setOpen(false)}>
              關閉
            </Button>
            {selectedView !== "uncategorized" && (
              <Button
                type="button"
                disabled={!draftName.trim() || saving || deleting}
                onClick={() => void saveCategory()}
              >
                {saving ? <Spinner data-icon="inline-start" /> : <SaveIcon data-icon="inline-start" />}
                {saveLabel}
              </Button>
            )}
          </SheetFooter>
        </SheetContent>
      </Sheet>
      <AlertDialog open={deleteOpen} onOpenChange={setDeleteOpen}>
        <AlertDialogContent>
          <AlertDialogHeader>
            <AlertDialogTitle>刪除分類「{selectedCategory?.name || "未命名分類"}」？</AlertDialogTitle>
            <AlertDialogDescription>
              分類刪除後，其中 {selectedCategory?.task_count ?? 0} 個任務會自動移入“未分類”，任務資料不會被刪除。
            </AlertDialogDescription>
          </AlertDialogHeader>
          <AlertDialogFooter>
            <AlertDialogCancel disabled={deleting}>取消</AlertDialogCancel>
            <AlertDialogAction
              variant="destructive"
              disabled={deleting}
              onClick={(event) => {
                event.preventDefault();
                void deleteCategory();
              }}
            >
              {deleting && <Spinner data-icon="inline-start" />}
              {deleting ? "刪除中" : "刪除"}
            </AlertDialogAction>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>
    </>
  );
}

function CreateTaskSheet({
  tasks,
  categories,
  onCreated,
  onCategoriesChanged,
}: {
  tasks: Task[];
  categories: TaskCategory[];
  onCreated: () => void;
  onCategoriesChanged: () => void;
}) {
  const [open, setOpen] = React.useState(false);
  const [name, setName] = React.useState("");
  const [categoryID, setCategoryID] = React.useState<number | undefined>(undefined);
  const [description, setDescription] = React.useState("");
  const [goal, setGoal] = React.useState("");
  const [selectedTemplateID, setSelectedTemplateID] = React.useState<number | null>(null);
  const [profiles, setProfiles] = React.useState<LLMProfile[]>([]);
  const [companies, setCompanies] = React.useState<Company[]>([]);
  const [sourceTaskIDs, setSourceTaskIDs] = React.useState<string[]>([]);
  const [companyIDs, setCompanyIDs] = React.useState<number[]>([]);
  const [llmProfileIDs, setLLMProfileIDs] = React.useState<string[]>([]);
  const [creating, setCreating] = React.useState(false);
  const [timeoutMin, setTimeoutMin] = React.useState(""); // 任務級超時(分鐘);空/0 = 不限時
  const [heartbeatMin, setHeartbeatMin] = React.useState("10"); // planner 心跳(分鐘);預設10,下限10(與後端一致)
  const [seedFirstIntent, setSeedFirstIntent] = React.useState(false); // 建立時下發種子意圖,worker 免等首輪 planner 直接開跑;預設關閉,走標準先規劃再執行
  const [coverageEnabled, setCoverageEnabled] = React.useState(true); // 資產覆蓋度功能;預設開。關閉=不計算/展示覆蓋度、不累積範圍、隱藏範圍類工具(company 關聯不受影響)
  const [interceptRules, setInterceptRules] = React.useState<AssetInterceptRuleInput[]>([]); // 任務級資產攔截規則(僅本任務生效,不進全域表)
  const [scheduleEnabled, setScheduleEnabled] = React.useState(false);
  const [schedule, setSchedule] = React.useState<ScheduleInput>({
    name: "新建任務計劃",
    schedule_type: "weekly",
    end_date: "",
    weekdays: [6, 7],
    start_time: "18:00",
    end_time: "",
    task_ids: [],
    timezone_mode: "beijing",
    start_immediately: false,
  });
  // 方式1 檔案上傳:建任務前把檔案暫存到 drafts/<draftId>/uploads/,拿回絕對路徑追加進描述。
  const [uploading, setUploading] = React.useState(false);
  const [uploadCount, setUploadCount] = React.useState(0);
  const draftIdRef = React.useRef<string>("");
  const fileInputRef = React.useRef<HTMLInputElement>(null);
  const sheetContentRef = React.useRef<HTMLDivElement>(null);

  // load LLM profiles once for the create-task profile picker.
  React.useEffect(() => {
    api
      .llmProfiles()
      .then(setProfiles)
      .catch(() => setProfiles([]));
    api
      .companies()
      .then(setCompanies)
      .catch(() => setCompanies([]));
  }, []);

  // pickFiles uploads the chosen files into this draft's staging dir and appends their
  // absolute paths to the description; the task's agents open them by path via Read/Bash.
  async function pickFiles(files: FileList | null) {
    if (!files || files.length === 0) return;
    // crypto.randomUUID 僅在安全上下文可用(https/localhost);經 IP+http 訪問時降級。
    if (!draftIdRef.current) {
      draftIdRef.current =
        globalThis.crypto?.randomUUID?.() ?? `d${Date.now().toString(36)}${Math.random().toString(36).slice(2, 10)}`;
    }
    setUploading(true);
    try {
      const r = await api.chatUpload("staging", draftIdRef.current, Array.from(files));
      setDescription((prev) => appendUploads(prev, r.attachments));
      setUploadCount((n) => n + r.attachments.length);
    } catch (e) {
      toast.error("上傳失敗：" + (e as Error).message);
    } finally {
      setUploading(false);
      if (fileInputRef.current) fileInputRef.current.value = ""; // allow re-picking the same file
    }
  }

  async function createTask() {
    if (!description.trim() || !goal.trim()) {
      toast.error("請填寫描述與目標");
      return;
    }
    if (sourceTaskIDs.length > MAX_SOURCE_TASKS) {
      toast.error(`最多關聯 ${MAX_SOURCE_TASKS} 個來源任務`);
      return;
    }
    setCreating(true);
    try {
      const timeoutSec = Math.max(0, Math.floor(Number(timeoutMin) || 0)) * 60;
      const heartbeatSec = Math.max(10, Math.floor(Number(heartbeatMin) || 10)) * 60; // 下限 10min，與後端歸一一致
      await api.createTask({
        name: name.trim(),
        categoryId: categoryID,
        description: description.trim(),
        goal: goal.trim(),
        llmProfileIds: llmProfileIDs.map(Number),
        sourceTaskIds: sourceTaskIDs,
        companyIds: companyIDs,
        timeoutSeconds: timeoutSec,
        seedFirstIntent,
        planHeartbeatSeconds: heartbeatSec,
        coverageEnabled,
        schedule: scheduleEnabled ? { ...schedule, task_ids: [] } : undefined,
        interceptRules: interceptRules
          .map((r) => ({ ...r, pattern: r.pattern.trim() }))
          .filter((r) => r.pattern !== ""),
      });
      toast.success("任務已建立");
      setName("");
      setCategoryID(undefined);
      setDescription("");
      setGoal("");
      setSelectedTemplateID(null);
      setSourceTaskIDs([]);
      setCompanyIDs([]);
      setLLMProfileIDs([]);
      setTimeoutMin("");
      setHeartbeatMin("10");
      setSeedFirstIntent(false);
      setCoverageEnabled(true);
      setInterceptRules([]);
      setScheduleEnabled(false);
      setSchedule({
        name: "新建任務計劃",
        schedule_type: "weekly",
        end_date: "",
        weekdays: [6, 7],
        start_time: "18:00",
        end_time: "",
        task_ids: [],
        timezone_mode: "beijing",
        start_immediately: false,
      });
      setUploadCount(0);
      draftIdRef.current = "";
      setOpen(false);
      onCreated();
    } catch (e) {
      toast.error("建立失敗：" + (e as Error).message);
    } finally {
      setCreating(false);
    }
  }

  return (
    <Sheet open={open} onOpenChange={setOpen}>
      <SheetTrigger asChild>
        <Button size="sm">
          <PlusIcon /> 新建任務
        </Button>
      </SheetTrigger>
      {/* 45vw 寬的右側抽屜:整屏高度可滾動,長表單不再受彈窗高度限制。窄屏退化為全寬。
            內容為 flex 列:頭/腳固定,中間欄位區 flex-1 獨立滾動。 */}
      <SheetContent
        ref={sheetContentRef}
        side="right"
        className="w-full! max-w-none! gap-0 p-0 sm:w-[45vw]! sm:max-w-[45vw]!"
      >
        <SheetHeader className="border-b p-6">
          <SheetTitle>新建任務</SheetTitle>
          <SheetDescription>填寫測試物件與目標，高階引數可按需展開。</SheetDescription>
        </SheetHeader>

        <div className="flex-1 overflow-y-auto p-6">
          <div className="grid gap-5">
            <TaskTemplateControls
              description={description}
              goal={goal}
              categoryID={categoryID}
              interceptRules={interceptRules}
              selectedTemplateID={selectedTemplateID}
              onSelectedTemplateIDChange={setSelectedTemplateID}
              onApply={(template) => {
                setDescription(template.description);
                setGoal(template.goal);
                setCategoryID(template.category_id ?? undefined);
                setInterceptRules(template.intercept_rules ?? []);
                setUploadCount(0);
              }}
              portalContainer={sheetContentRef}
            />
            <div className="grid gap-2">
              <Label htmlFor="name">名稱（可選）</Label>
              <Input
                id="name"
                placeholder="給任務起個便於識別的名字，例如：Acme 官網滲透"
                value={name}
                onChange={(e) => setName(e.target.value)}
              />
            </div>
            <Field>
              <FieldLabel htmlFor="task-category">任務分類</FieldLabel>
              <CategoryPicker
                categories={categories}
                value={categoryID}
                onValueChange={setCategoryID}
                onCategoryCreated={onCategoriesChanged}
                portalContainer={sheetContentRef}
              />
              <FieldDescription>可選，單個分類；用於任務列表篩選和歸檔，不影響 Agent 執行。</FieldDescription>
            </Field>
            <FieldSet>
              <FieldLegend>計劃啟動（可選）</FieldLegend>
              <label className="flex items-center gap-2 text-sm">
                <Checkbox checked={scheduleEnabled} onCheckedChange={(v) => setScheduleEnabled(!!v)} />
                建立時附加計劃，按時間視窗啟動和暫停
              </label>
              {scheduleEnabled && (
                <FieldGroup className="rounded-lg border p-3">
                  <Field>
                    <FieldLabel>計劃名稱</FieldLabel>
                    <Input value={schedule.name} onChange={(e) => setSchedule({ ...schedule, name: e.target.value })} />
                  </Field>
                  <div className="grid grid-cols-2 gap-3">
                    <Field>
                      <FieldLabel>規則</FieldLabel>
                      <Select
                        value={schedule.schedule_type}
                        onValueChange={(value) =>
                          setSchedule({ ...schedule, schedule_type: value as ScheduleInput["schedule_type"] })
                        }
                      >
                        <SelectTrigger className="h-10 w-full bg-background">
                          <SelectValue />
                        </SelectTrigger>
                        <SelectContent>
                          <SelectItem value="weekly">按週</SelectItem>
                          <SelectItem value="once">指定日期</SelectItem>
                        </SelectContent>
                      </Select>
                    </Field>
                    <Field>
                      <FieldLabel>時區</FieldLabel>
                      <Select
                        value={schedule.timezone_mode}
                        onValueChange={(value) =>
                          setSchedule({ ...schedule, timezone_mode: value as ScheduleInput["timezone_mode"] })
                        }
                      >
                        <SelectTrigger className="h-10 w-full bg-background">
                          <SelectValue />
                        </SelectTrigger>
                        <SelectContent>
                          <SelectItem value="beijing">北京時間</SelectItem>
                          <SelectItem value="system">系統時區</SelectItem>
                        </SelectContent>
                      </Select>
                    </Field>
                  </div>
                  {schedule.schedule_type === "once" ? (
                    <div className="grid grid-cols-2 gap-3">
                      <Field>
                        <FieldLabel>開始日期</FieldLabel>
                        <DateSelect
                          value={schedule.run_date ?? ""}
                          onValueChange={(value) => setSchedule({ ...schedule, run_date: value })}
                          aria-label="開始日期"
                        />
                      </Field>
                      <Field>
                        <FieldLabel>截止日期（可選）</FieldLabel>
                        <DateSelect
                          value={schedule.end_date ?? ""}
                          onValueChange={(value) => setSchedule({ ...schedule, end_date: value })}
                          optional
                          placeholder="不設定截止日期"
                          aria-label="截止日期，可選"
                        />
                      </Field>
                    </div>
                  ) : (
                    <Field>
                      <FieldLabel>星期（1=週一，7=週日）</FieldLabel>
                      <Input
                        value={(schedule.weekdays ?? []).join(",")}
                        onChange={(e) =>
                          setSchedule({
                            ...schedule,
                            weekdays: e.target.value
                              .split(",")
                              .map(Number)
                              .filter((n) => n >= 1 && n <= 7),
                          })
                        }
                        placeholder="例如 6,7"
                      />
                    </Field>
                  )}
                  <div className="grid grid-cols-2 gap-3">
                    <Field>
                      <FieldLabel>開始時間</FieldLabel>
                      <TimeSelect
                        value={schedule.start_time}
                        onValueChange={(value) => setSchedule({ ...schedule, start_time: value })}
                        aria-label="開始時間"
                      />
                    </Field>
                    <Field>
                      <FieldLabel>結束時間（可選）</FieldLabel>
                      <TimeSelect
                        value={schedule.end_time ?? ""}
                        onValueChange={(value) => setSchedule({ ...schedule, end_time: value })}
                        optional
                        aria-label="結束時間，可選"
                      />
                    </Field>
                  </div>
                  <label className="flex items-center gap-2 text-sm">
                    <Checkbox
                      checked={schedule.start_immediately}
                      onCheckedChange={(v) => setSchedule({ ...schedule, start_immediately: !!v })}
                    />
                    建立後立即啟動，否則等待第一個計劃視窗
                  </label>
                </FieldGroup>
              )}
            </FieldSet>
            <div className="grid gap-2">
              <Label htmlFor="description">描述</Label>
              <Textarea
                id="description"
                className="min-h-32"
                placeholder="測試物件與背景，例如：測試 example.com 這個站點"
                value={description}
                onChange={(e) => setDescription(e.target.value)}
              />
              {/* 上傳檔案(可多選):暫存到 drafts/,把絕對路徑追加進上方描述,worker 據此 Read/Bash 開啟。 */}
              <div className="flex flex-wrap items-center gap-2">
                <input
                  ref={fileInputRef}
                  type="file"
                  multiple
                  className="hidden"
                  onChange={(e) => void pickFiles(e.target.files)}
                />
                <Button
                  type="button"
                  variant="outline"
                  size="sm"
                  onClick={() => fileInputRef.current?.click()}
                  disabled={uploading}
                >
                  {uploading ? <Loader2Icon className="animate-spin" /> : <PaperclipIcon />}
                  上傳檔案
                </Button>
                <span className="text-muted-foreground text-xs">
                  {uploadCount > 0
                    ? `已上傳 ${uploadCount} 個檔案，絕對路徑已追加到描述末尾（可編輯）`
                    : "可多選；上傳後把檔案的絕對路徑追加到描述，供 worker 用 Read/Bash 開啟"}
                </span>
              </div>
            </div>
            <div className="grid gap-2">
              <Label htmlFor="goal">目標</Label>
              <Textarea
                id="goal"
                className="min-h-32"
                placeholder="要達成什麼，例如：拿下後臺管理權限、獲取伺服器權限"
                value={goal}
                onChange={(e) => setGoal(e.target.value)}
              />
            </div>
            <Field>
              <FieldLabel htmlFor="source-tasks">關聯任務</FieldLabel>
              <SourceTaskPicker
                tasks={tasks}
                value={sourceTaskIDs}
                onValueChange={setSourceTaskIDs}
                portalContainer={sheetContentRef}
              />
              <FieldDescription>
                最多關聯 {MAX_SOURCE_TASKS}{" "}
                個任務。即時只讀繼承所選任務的持久化黑板、資產範圍及相關流量；新任務寫入獨立黑板。
              </FieldDescription>
            </Field>
            <Field>
              <FieldLabel htmlFor="task-companies">關聯企業資產範圍</FieldLabel>
              <CompanyPicker
                companies={companies}
                value={companyIDs}
                onValueChange={setCompanyIDs}
                portalContainer={sheetContentRef}
              />
              <FieldDescription>
                建立任務時會將所選企業當前已有資產加入“測試資產”，並將域名、IP、CIDR、ICP 和企業關鍵詞提供給 Agent
                作為範圍上下文；不會自動生成意圖或強制改變執行目標。
              </FieldDescription>
            </Field>
            <Field>
              <FieldLabel htmlFor="task-intercept-rules">任務級資產攔截 / 允許規則（可選）</FieldLabel>
              <AssetInterceptRulesEditor value={interceptRules} onChange={setInterceptRules} />
              <FieldDescription>
                僅對本任務生效，不寫入全域規則。判定順序：先按「攔截」規則（含全域）匹配，命中即禁止測試；未命中且本任務配置了「允許」規則時，須命中某條允許規則才放行，否則同樣不允許測試；未配置任何允許規則則不啟用白名單。
              </FieldDescription>
            </Field>
            <Field>
              <FieldLabel htmlFor="llm-profiles">LLM 配置鏈</FieldLabel>
              <TaskLLMProfileChain
                profiles={profiles}
                value={llmProfileIDs}
                onValueChange={setLLMProfileIDs}
                inputId="llm-profiles"
                portalContainer={sheetContentRef}
              />
              <FieldDescription>按列表順序故障轉移；第一項為當前配置，僅在明確額度不足時切換下一項。</FieldDescription>
            </Field>

            {/* 高階引數預設摺疊:超時/心跳/首個意圖,展開才佔空間,常用路徑保持清爽。 */}
            <Collapsible>
              <CollapsibleTrigger className="group flex w-full items-center gap-2 border-t pt-4 text-sm font-medium">
                <ChevronRightIcon className="text-muted-foreground size-4 transition-transform group-data-[state=open]:rotate-90" />
                進階設定
                <span className="text-muted-foreground ml-auto text-xs font-normal">超時 · 心跳 · 首個意圖</span>
              </CollapsibleTrigger>
              <CollapsibleContent className="grid gap-5 pt-5">
                <div className="grid gap-2">
                  <Label htmlFor="timeout-min">任務超時（分鐘，可選）</Label>
                  <Input
                    id="timeout-min"
                    type="number"
                    min={0}
                    className="w-40"
                    placeholder="留空 = 不限時"
                    value={timeoutMin}
                    onChange={(e) => setTimeoutMin(e.target.value)}
                  />
                  <p className="text-muted-foreground text-xs">
                    到點後觸發優雅收尾（各 agent 寫回 + planner 終局判定），任務進入 timeout 終態。
                  </p>
                </div>
                <div className="grid gap-2">
                  <Label htmlFor="heartbeat-min">planner 心跳（分鐘）</Label>
                  <Input
                    id="heartbeat-min"
                    type="number"
                    min={10}
                    className="w-40"
                    placeholder="預設 10"
                    value={heartbeatMin}
                    onChange={(e) => setHeartbeatMin(e.target.value)}
                  />
                  <p className="text-muted-foreground text-xs">
                    距上輪規劃結束/任務開始滿該時長且期間無觸發，自動觸發一輪規劃（兜底卡死 + 喚醒去監督在跑的
                    worker）。下限 10 分鐘。
                  </p>
                </div>
                <div className="grid gap-2">
                  <label htmlFor="seed-first-intent" className="flex items-center gap-2 text-sm">
                    <Checkbox
                      id="seed-first-intent"
                      checked={seedFirstIntent}
                      onCheckedChange={(v) => setSeedFirstIntent(!!v)}
                    />
                    直接下發首個意圖（描述+目標）
                  </label>
                  <p className="text-muted-foreground text-xs">
                    開啟後建立即把「描述+目標」作為一條意圖下發，worker 免等首輪規劃直接開跑，跑完再由 planner
                    接手判定/補充。CTF 等常一個 work 直接解決的場景推薦開啟；關閉則走標準的先規劃再執行。
                  </p>
                </div>
                <div className="grid gap-2">
                  <label htmlFor="coverage-enabled" className="flex items-center gap-2 text-sm">
                    <Checkbox
                      id="coverage-enabled"
                      checked={coverageEnabled}
                      onCheckedChange={(v) => setCoverageEnabled(!!v)}
                    />
                    資產覆蓋度功能
                  </label>
                  <p className="text-muted-foreground text-xs">
                    預設開啟：計算並展示測試覆蓋度、態勢圖顯示測試進度、自動累積測試範圍。關閉後不再計算/展示覆蓋度，
                    態勢圖僅展示資產不顯示進度，agent 也不再獲得範圍類工具。關閉不影響「關聯企業資產範圍」。
                  </p>
                </div>
              </CollapsibleContent>
            </Collapsible>
          </div>
        </div>

        <SheetFooter className="flex-row justify-end gap-2 border-t p-4">
          <SheetClose asChild>
            <Button variant="outline">取消</Button>
          </SheetClose>
          <Button onClick={createTask} disabled={creating || uploading}>
            {creating && <Spinner data-icon="inline-start" />}
            {creating ? "建立中" : "建立"}
          </Button>
        </SheetFooter>
      </SheetContent>
    </Sheet>
  );
}
